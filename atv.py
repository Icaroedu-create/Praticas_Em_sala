entrada = input("digite alguma coisa: ")

# funadamentos:

print("E numerico?", entrada.isnumeric())
print("E alfabetico?" , entrada.isalpha())
print("E alfabetico?", entrada.isalnum())
print("E decimal?", entrada.isdecimal())
print("Possui apenas espaço?", entrada.isspace())
print("Esta em maiusculo?", entrada.isupper())
print("Esta em minusculo?",entrada.islower())
